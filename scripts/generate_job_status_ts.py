"""Generate the standalone TypeScript job-state vocabulary from canonical Core Python."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from app.job_states import JobStatus, TERMINAL_STATUSES

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "web/src/job-statuses.generated.ts"


def render() -> str:
    states = sorted(item.value for item in JobStatus)
    terminal = sorted(item.value for item in TERMINAL_STATUSES)
    if not terminal or not set(terminal).issubset(states):
        raise ValueError("All terminal statuses must belong to the Core enum")
    return (
        "// GENERATED by scripts/generate_job_status_ts.py from app/job_states.py.\n"
        "// Do not edit manually; run python -m scripts.generate_job_status_ts.\n"
        f"export const JOB_STATUSES = {json.dumps(states)} as const;\n"
        "export type JobStatus = typeof JOB_STATUSES[number];\n"
        f"export const TERMINAL_JOB_STATUSES: ReadonlySet<string> = new Set({json.dumps(terminal)});\n"
        "export function isTerminalStatus(status: unknown): boolean {\n"
        "  return typeof status === 'string' && TERMINAL_JOB_STATUSES.has(status);\n"
        "}\n"
        "export function isKnownJobStatus(status: unknown): status is JobStatus {\n"
        "  return typeof status === 'string' && JOB_STATUSES.includes(status as JobStatus);\n"
        "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Generated UI job states drifted from Core; regenerate and commit")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
